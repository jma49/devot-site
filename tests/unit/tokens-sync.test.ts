import { readFileSync, rmSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { describe, expect, it } from 'vitest'
import {
  modeFromArgs,
  OUTPUTS,
  PIN_FILE,
  syncTokens,
  TokenSyncError,
  type FetchText,
} from '../../scripts/tokens/sync.ts'
import { tempDir } from '../support/temp-dirs.ts'

const OLD = 'a'.repeat(40)
const NEW = 'b'.repeat(40)
const RAW = 'https://raw.githubusercontent.com/jma49/devot'
const HEAD_API = 'https://api.github.com/repos/jma49/devot/commits/main'

const CSS_BODY = ':root {\n  --color-text-primary: #212121;\n}\n'
const DEVOT_CSS = `/* Generated by scripts/tokens/build.ts from design/tokens. Do not edit. */\n${CSS_BODY}`
const ink = (top: string, bottom: string, y = '2') =>
  `<linearGradient id="devot-ink" gradientUnits="userSpaceOnUse" x1="0" y1="${y}" x2="0" y2="72"><stop offset="0" stop-color="${top}"/><stop offset="1" stop-color="${bottom}"/></linearGradient>`
const SVG = `<svg xmlns="http://www.w3.org/2000/svg"><defs>${ink('#111111', '#222222')}</defs><path fill="url(#devot-ink)" d="M0 0"/></svg>\n`
const LOCKUP_DARK = `<svg xmlns="http://www.w3.org/2000/svg"><defs>${ink('#aaaaaa', '#bbbbbb', '4')}</defs><path fill="url(#devot-ink)" d="M9 9"/><path d="M1 1"/></svg>\n`
const ICON = (name: string) =>
  `<svg xmlns="http://www.w3.org/2000/svg"><title>${name}</title></svg>\n`
const ICONS = ['source.svg', 'source-small.svg', 'source-ios.svg']

function devotAt(commit: string, overrides: Record<string, string> = {}): Record<string, string> {
  return {
    [`${RAW}/${commit}/src/renderer/src/theme/tokens.css`]: DEVOT_CSS,
    [`${RAW}/${commit}/design/app-icon/dove.svg`]: SVG,
    [`${RAW}/${commit}/design/app-icon/lockup-dark.svg`]: LOCKUP_DARK,
    ...Object.fromEntries(
      ICONS.map((name) => [`${RAW}/${commit}/design/app-icon/${name}`, ICON(name)]),
    ),
    [HEAD_API]: JSON.stringify({ sha: NEW, commit: { message: 'unrelated' } }),
    ...overrides,
  }
}

function fakeFetch(responses: Record<string, string>): FetchText & { urls: string[] } {
  const urls: string[] = []
  const fetchText = async (url: string) => {
    urls.push(url)
    const body = responses[url]
    if (body === undefined) throw new Error(`404 ${url}`)
    return body
  }
  return Object.assign(fetchText, { urls })
}

function siteAt(commit: string | null): string {
  const root = tempDir('devot-site-tokens-')
  if (commit !== null) writeFileSync(join(root, PIN_FILE), JSON.stringify({ commit }))
  return root
}

const read = (root: string, path: string) => readFileSync(join(root, path), 'utf8')

async function failure(run: Promise<unknown>): Promise<TokenSyncError> {
  const error = await run.then(
    () => null,
    (e: unknown) => e,
  )
  expect(error).toBeInstanceOf(TokenSyncError)
  return error as TokenSyncError
}

describe('pnpm tokens', () => {
  it('writes the tokens, the dove and the app icons from the pinned commit', async () => {
    const root = siteAt(OLD)
    const fetchText = fakeFetch(devotAt(OLD))

    await syncTokens('write', { root, fetchText })

    expect(new Set(fetchText.urls)).toEqual(
      new Set(
        [
          'design/app-icon/dove.svg',
          'design/app-icon/lockup-dark.svg',
          'design/app-icon/source-ios.svg',
          'design/app-icon/source-small.svg',
          'design/app-icon/source.svg',
          'src/renderer/src/theme/tokens.css',
        ].map((path) => `${RAW}/${OLD}/${path}`),
      ),
    )
    expect(read(root, 'src/theme/tokens.css')).toBe(
      `/* Generated from jma49/devot@${OLD} (src/renderer/src/theme/tokens.css). Do not edit. */\n${CSS_BODY}`,
    )
    expect(read(root, 'src/assets/dove.svg')).toBe(
      `<!-- Generated from jma49/devot@${OLD} (design/app-icon/dove.svg). Do not edit. -->\n${SVG}`,
    )
    for (const [from, to] of [
      ['source.svg', 'app-icon.svg'],
      ['source-small.svg', 'app-icon-small.svg'],
      ['source-ios.svg', 'app-icon-ios.svg'],
    ]) {
      expect(read(root, `src/assets/${to}`)).toBe(
        `<!-- Generated from jma49/devot@${OLD} (design/app-icon/${from}). Do not edit. -->\n${ICON(from ?? '')}`,
      )
    }
  })

  it("writes the dark dove: the dove's shape in the ink of the lockup for dark grounds", async () => {
    const root = siteAt(OLD)

    await syncTokens('write', { root, fetchText: fakeFetch(devotAt(OLD)) })

    const [header, ...body] = read(root, 'src/assets/dove-dark.svg').split('\n')
    expect(header).toBe(
      `<!-- Generated from jma49/devot@${OLD} (design/app-icon/dove.svg, its ink from design/app-icon/lockup-dark.svg). Do not edit. -->`,
    )
    expect(body.join('\n')).toBe(SVG.replace('#111111', '#aaaaaa').replace('#222222', '#bbbbbb'))
  })

  it('fails with E_TOKENS_SHAPE when a file lacks the ink gradient the dark dove needs', async () => {
    for (const file of ['dove.svg', 'lockup-dark.svg']) {
      const root = siteAt(OLD)
      const url = `${RAW}/${OLD}/design/app-icon/${file}`
      const fetchText = fakeFetch(devotAt(OLD, { [url]: '<svg><path d="M0 0"/></svg>\n' }))

      const error = await failure(syncTokens('write', { root, fetchText }))

      expect(error.code).toBe('E_TOKENS_SHAPE')
      expect(error.message).toContain(`design/app-icon/${file}`)
    }
  })

  it("keeps the stylesheet as is when devot's own header is missing", async () => {
    const root = siteAt(OLD)
    const url = `${RAW}/${OLD}/src/renderer/src/theme/tokens.css`

    await syncTokens('write', { root, fetchText: fakeFetch(devotAt(OLD, { [url]: CSS_BODY })) })

    expect(read(root, 'src/theme/tokens.css').split('\n').slice(1).join('\n')).toBe(CSS_BODY)
  })

  it('reports a failed download with its code and URL', async () => {
    const root = siteAt(OLD)
    const url = `${RAW}/${OLD}/design/app-icon/dove.svg`
    const responses = devotAt(OLD)
    delete responses[url]

    const error = await failure(syncTokens('write', { root, fetchText: fakeFetch(responses) }))

    expect(error.code).toBe('E_TOKENS_FETCH')
    expect(error.message).toContain(url)
  })

  it('refuses a missing or malformed pin', async () => {
    for (const pin of [null, 'main', 'A'.repeat(40), 'a'.repeat(39)]) {
      const root = siteAt(pin)
      const error = await failure(syncTokens('write', { root, fetchText: fakeFetch(devotAt(OLD)) }))
      expect(error.code).toBe('E_TOKENS_PIN')
    }
  })
})

describe('pnpm tokens:check', () => {
  it('passes when the committed output matches the pin', async () => {
    const root = siteAt(OLD)
    await syncTokens('write', { root, fetchText: fakeFetch(devotAt(OLD)) })

    await expect(
      syncTokens('check', { root, fetchText: fakeFetch(devotAt(OLD)) }),
    ).resolves.toContain(OLD)
  })

  it('fails with E_TOKENS_STALE, naming the file, after a hand edit, and leaves it alone', async () => {
    const root = siteAt(OLD)
    await syncTokens('write', { root, fetchText: fakeFetch(devotAt(OLD)) })
    writeFileSync(join(root, 'src/theme/tokens.css'), 'edited')

    const error = await failure(syncTokens('check', { root, fetchText: fakeFetch(devotAt(OLD)) }))

    expect(error.code).toBe('E_TOKENS_STALE')
    expect(error.message).toContain('src/theme/tokens.css')
    expect(error.message).not.toContain('src/assets/dove.svg')
    expect(read(root, 'src/theme/tokens.css')).toBe('edited')
  })

  it('fails when an output is missing or the pin moved without regenerating', async () => {
    const root = siteAt(OLD)
    await syncTokens('write', { root, fetchText: fakeFetch(devotAt(OLD)) })
    rmSync(join(root, 'src/assets/dove.svg'))

    const missing = await failure(syncTokens('check', { root, fetchText: fakeFetch(devotAt(OLD)) }))
    expect(missing.code).toBe('E_TOKENS_STALE')
    expect(missing.message).toContain('src/assets/dove.svg')

    await syncTokens('write', { root, fetchText: fakeFetch(devotAt(OLD)) })
    writeFileSync(join(root, PIN_FILE), JSON.stringify({ commit: NEW }))
    const moved = await failure(syncTokens('check', { root, fetchText: fakeFetch(devotAt(NEW)) }))
    expect(moved.code).toBe('E_TOKENS_STALE')
  })
})

describe('pnpm tokens:update', () => {
  it("moves the pin to devot main's HEAD and regenerates from it", async () => {
    const root = siteAt(OLD)
    await syncTokens('write', { root, fetchText: fakeFetch(devotAt(OLD)) })

    await syncTokens('update', { root, fetchText: fakeFetch(devotAt(NEW)) })

    expect(read(root, PIN_FILE)).toBe(`{\n  "commit": "${NEW}"\n}\n`)
    expect(read(root, 'src/theme/tokens.css')).toContain(`jma49/devot@${NEW}`)
    expect(read(root, 'src/assets/dove.svg')).toContain(`jma49/devot@${NEW}`)
  })

  it('works without an existing pin', async () => {
    const root = siteAt(null)

    await syncTokens('update', { root, fetchText: fakeFetch(devotAt(NEW)) })

    expect(JSON.parse(read(root, PIN_FILE))).toEqual({ commit: NEW })
  })

  it('refuses an answer from GitHub that is not a commit SHA and keeps the old pin', async () => {
    for (const answer of ['{"message":"Not Found"}', '{"sha":"main"}', 'not json']) {
      const root = siteAt(OLD)
      const fetchText = fakeFetch(devotAt(NEW, { [HEAD_API]: answer }))

      const error = await failure(syncTokens('update', { root, fetchText }))

      expect(error.code).toBe('E_TOKENS_FETCH')
      expect(JSON.parse(read(root, PIN_FILE))).toEqual({ commit: OLD })
    }
  })

  it('keeps the old pin and outputs when a download fails', async () => {
    const root = siteAt(OLD)
    await syncTokens('write', { root, fetchText: fakeFetch(devotAt(OLD)) })
    const before = OUTPUTS.map(({ to }) => read(root, to))
    const responses = devotAt(NEW)
    delete responses[`${RAW}/${NEW}/design/app-icon/dove.svg`]

    const error = await failure(syncTokens('update', { root, fetchText: fakeFetch(responses) }))

    expect(error.code).toBe('E_TOKENS_FETCH')
    expect(JSON.parse(read(root, PIN_FILE))).toEqual({ commit: OLD })
    expect(OUTPUTS.map(({ to }) => read(root, to))).toEqual(before)
  })
})

describe('the command line', () => {
  it('takes no flag, --check or --update', () => {
    expect(modeFromArgs([])).toBe('write')
    expect(modeFromArgs(['--check'])).toBe('check')
    expect(modeFromArgs(['--update'])).toBe('update')
  })

  it('refuses anything else, so a mistyped --check never rewrites the files', () => {
    for (const args of [['--chek'], ['check'], ['--check', '--update'], ['--check', 'x']]) {
      let error: unknown
      try {
        modeFromArgs(args)
      } catch (e) {
        error = e
      }
      expect(error, args.join(' ')).toBeInstanceOf(TokenSyncError)
      expect((error as TokenSyncError).code).toBe('E_TOKENS_ARGS')
    }
  })
})

describe('the committed output', () => {
  it('names the pinned commit in every generated header', () => {
    const repo = join(import.meta.dirname, '../..')
    const { commit } = JSON.parse(read(repo, PIN_FILE)) as { commit: string }

    expect(commit).toMatch(/^[0-9a-f]{40}$/)
    for (const { to } of OUTPUTS) {
      expect(read(repo, to).split('\n')[0], to).toContain(`Generated from jma49/devot@${commit}`)
    }
  })
})
