// The palettes of the official theme plugins, as their authors publish them (each plugin's LICENSE names its source).
// `neutrals` are the grays from darkest to lightest or the other way round, `hues` the colored ones;
// `background` and `text` are the editor's ground and ink, `accent` the color of buttons, links and selection.

export interface Palette {
  /** Theme ID in the manifest and file name in the package. */
  id: string
  title: string
  appearance: 'light' | 'dark'
  background: string
  text: string
  accent: string
  neutrals: readonly string[]
  hues: readonly string[]
}

export interface ThemeFamily {
  /** Folder under `plugins/`. */
  folder: string
  palettes: readonly Palette[]
}

const catppuccin = (
  id: string,
  title: string,
  appearance: 'light' | 'dark',
  c: Record<string, string>,
): Palette => ({
  id,
  title,
  appearance,
  background: c['base']!,
  text: c['text']!,
  accent: c['mauve']!,
  neutrals: [
    'crust',
    'mantle',
    'base',
    'surface0',
    'surface1',
    'surface2',
    'overlay0',
    'overlay1',
    'overlay2',
    'subtext0',
    'subtext1',
    'text',
  ].map((k) => c[k]!),
  hues: [
    'red',
    'maroon',
    'peach',
    'yellow',
    'green',
    'teal',
    'sky',
    'sapphire',
    'blue',
    'lavender',
    'mauve',
    'pink',
    'flamingo',
  ].map((k) => c[k]!),
})

