import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'

export const DEVOT_REPO = 'jma49/devot'
export const PIN_FILE = 'devot.pin.json'

interface Output {
  from: string
  to: string
  /** A Devot file whose `devot-ink` gradient replaces the one in `from`. */
  ink?: string
}

export const OUTPUTS: readonly Output[] = [
  { from: 'src/renderer/src/theme/tokens.css', to: 'src/theme/tokens.css' },
  { from: 'design/app-icon/dove.svg', to: 'src/assets/dove.svg' },
  // Devot has no dark dove of its own; its lockup for dark grounds carries the ink.
  {
    from: 'design/app-icon/dove.svg',
    ink: 'design/app-icon/lockup-dark.svg',
    to: 'src/assets/dove-dark.svg',
  },
  { from: 'design/app-icon/source.svg', to: 'src/assets/app-icon.svg' },
  { from: 'design/app-icon/source-small.svg', to: 'src/assets/app-icon-small.svg' },
  { from: 'design/app-icon/source-ios.svg', to: 'src/assets/app-icon-ios.svg' },
]

export type FetchText = (url: string) => Promise<string>

export type SyncMode = 'write' | 'check' | 'update'

export type TokenSyncCode =
  | 'E_TOKENS_STALE'
  | 'E_TOKENS_FETCH'
  | 'E_TOKENS_PIN'
  | 'E_TOKENS_ARGS'
  | 'E_TOKENS_SHAPE'

export class TokenSyncError extends Error {
  readonly code: TokenSyncCode

  constructor(code: TokenSyncCode, detail: string) {
    super(`${code} ${detail}`)
    this.code = code
  }
}

const FLAGS: Record<string, SyncMode> = { '--check': 'check', '--update': 'update' }

export function modeFromArgs(args: string[]): SyncMode {
  if (args.length === 0) return 'write'
  const mode = args.length === 1 ? FLAGS[args[0] as string] : undefined
  if (!mode) throw new TokenSyncError('E_TOKENS_ARGS', 'expected no flag, --check or --update')
  return mode
}

const SHA = /^[0-9a-f]{40}$/
// devot's own header names its build script, which does not exist here.
const DEVOT_HEADER = /^\/\* Generated by [^\n]*\*\/\n/
const INK = /(<linearGradient\b[^>]*\bid="devot-ink"[^>]*>)([\s\S]*?)(<\/linearGradient>)/

/**
 * `write` regenerates the outputs from the pinned commit, `check` fails with E_TOKENS_STALE when
 * the files on disk differ from that, `update` first moves the pin to devot main's HEAD.
 */
export async function syncTokens(
  mode: SyncMode,
  { root, fetchText }: { root: string; fetchText: FetchText },
): Promise<string> {
  const commit = mode === 'update' ? await resolveMain(fetchText) : readPin(root)
  const outputs = await generate(commit, fetchText)

  if (mode === 'check') {
    const stale = outputs.filter(({ to, content }) => readOrNull(join(root, to)) !== content)
    if (stale.length > 0) {
      throw new TokenSyncError(
        'E_TOKENS_STALE',
        `${stale.map(({ to }) => to).join(' ')} (pinned ${DEVOT_REPO}@${commit}): run pnpm tokens`,
      )
    }
    return `tokens match ${DEVOT_REPO}@${commit}`
  }

  if (mode === 'update')
    writeFileSync(join(root, PIN_FILE), `${JSON.stringify({ commit }, null, 2)}\n`)
  for (const { to, content } of outputs) {
    mkdirSync(dirname(join(root, to)), { recursive: true })
    writeFileSync(join(root, to), content)
  }
  return `wrote ${outputs.map(({ to }) => to).join(' ')} from ${DEVOT_REPO}@${commit}`
}

async function generate(commit: string, fetchText: FetchText) {
  const paths = [...new Set(OUTPUTS.flatMap(({ from, ink }) => (ink ? [from, ink] : [from])))]
  const bodies = new Map(
    await Promise.all(
      paths.map(
        async (path) =>
          [
            path,
            await get(
              fetchText,
              `https://raw.githubusercontent.com/${DEVOT_REPO}/${commit}/${path}`,
            ),
          ] as const,
      ),
    ),
  )
  const body = (path: string) => bodies.get(path) ?? ''
  return OUTPUTS.map(({ from, to, ink }) => {
    const source = ink ? `${from}, its ink from ${ink}` : from
    const header = `Generated from ${DEVOT_REPO}@${commit} (${source}). Do not edit.`
    const text = ink ? withInk(body(from), from, body(ink), ink) : body(from)
    const content = to.endsWith('.css')
      ? `/* ${header} */\n${text.replace(DEVOT_HEADER, '')}`
      : `<!-- ${header} -->\n${text}`
    return { to, content }
  })
}

function withInk(svg: string, path: string, inkSvg: string, inkPath: string): string {
  const stops = INK.exec(inkSvg)?.[2]
  const missing = !INK.test(svg) ? path : stops === undefined ? inkPath : undefined
  if (missing) throw new TokenSyncError('E_TOKENS_SHAPE', `${missing} has no devot-ink gradient`)
  return svg.replace(INK, (_, open: string, _stops: string, close: string) => open + stops + close)
}

async function resolveMain(fetchText: FetchText): Promise<string> {
  const url = `https://api.github.com/repos/${DEVOT_REPO}/commits/main`
  const answer = await get(fetchText, url)
  let sha: unknown
  try {
    sha = (JSON.parse(answer) as { sha?: unknown }).sha
  } catch {
    sha = undefined
  }
  if (typeof sha !== 'string' || !SHA.test(sha)) {
    throw new TokenSyncError('E_TOKENS_FETCH', `${url} did not return a commit SHA`)
  }
  return sha
}

function readPin(root: string): string {
  const text = readOrNull(join(root, PIN_FILE))
  let commit: unknown
  try {
    commit = text === null ? undefined : (JSON.parse(text) as { commit?: unknown }).commit
  } catch {
    commit = undefined
  }
  if (typeof commit !== 'string' || !SHA.test(commit)) {
    throw new TokenSyncError('E_TOKENS_PIN', `${PIN_FILE} must hold {"commit": "<40-hex SHA>"}`)
  }
  return commit
}

async function get(fetchText: FetchText, url: string): Promise<string> {
  try {
    return await fetchText(url)
  } catch (error) {
    throw new TokenSyncError('E_TOKENS_FETCH', `${url}: ${(error as Error).message}`)
  }
}

function readOrNull(path: string): string | null {
  try {
    return readFileSync(path, 'utf8')
  } catch {
    return null
  }
}
